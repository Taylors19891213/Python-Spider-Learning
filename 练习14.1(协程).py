import time
def func():
    print("1")
    time.sleep(3)     #让当前的线程处于阻塞状态，CPU是不为我工作的
    print("2")
if __name__ == '__main__':
    func()

# 一般情况下，程序处于IO操作的时候，线程都会处于阻塞状态
# input()
# requests.get(......)


# 协程：当程序遇见IO操作的时候，可以选择性地切换到其他任务上
# 在微观上是一个人物一个任务的切换，切换条件一般是IO操作
# 在宏观上，我们能看到的其实是多个任务一起在执行
# 多任务异步操作
# 均在单线程条件下